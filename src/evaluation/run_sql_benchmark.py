# =========================================================
# LOAD BENCHMARK CSV
# =========================================================

def load_benchmark():

    if not BENCHMARK_PATH.exists():

        raise FileNotFoundError(
            f"Benchmark file not found:\n"
            f"{BENCHMARK_PATH}"
        )


    rows = []


    with open(
        BENCHMARK_PATH,
        "r",
        encoding="utf-8-sig",
        newline="",
    ) as file:

        reader = csv.DictReader(
            file
        )


        required_columns = {
            "id",
            "category",
            "difficulty",
            "question",
        }


        actual_columns = set(
            reader.fieldnames
            or []
        )


        missing_columns = (
            required_columns
            - actual_columns
        )


        if missing_columns:

            raise ValueError(
                "Benchmark CSV is missing "
                f"columns: "
                f"{sorted(missing_columns)}"
            )


        for row in reader:

            rows.append(
                row
            )


    return rows


# =========================================================
# RUN TRUSTED REFERENCE SQL
# =========================================================

def run_reference_sql(
    benchmark_id,
):

    if benchmark_id not in REFERENCE_SQL:

        raise KeyError(
            "No trusted reference SQL "
            f"exists for {benchmark_id}"
        )


    if not DB_PATH.exists():

        raise FileNotFoundError(
            f"Database not found:\n"
            f"{DB_PATH}"
        )


    sql = (
        REFERENCE_SQL[
            benchmark_id
        ]
    )


    connection = duckdb.connect(
        str(DB_PATH),
        read_only=True,
    )


    try:

        dataframe = (
            connection
            .execute(
                sql
            )
            .df()
        )


    finally:

        connection.close()


    return dataframe


# =========================================================
# NORMALIZE INDIVIDUAL VALUES
# =========================================================

def normalize_value(
    value,
):

    if pd.isna(
        value
    ):

        return (
            "null",
            None,
        )


    if isinstance(
        value,
        bool,
    ):

        return (
            "bool",
            bool(value),
        )


    if isinstance(
        value,
        numbers.Number,
    ):

        return (
            "number",
            round(
                float(value),
                2,
            ),
        )


    text = (
        str(value)
        .strip()
        .upper()
    )


    return (
        "text",
        text,
    )


# =========================================================
# TURN DATAFRAME INTO COMPARABLE VALUE COUNTER
# =========================================================

def dataframe_counter(
    dataframe,
):

    normalized_values = []


    if dataframe is None:

        return Counter()


    for value in (
        dataframe
        .to_numpy()
        .flatten()
        .tolist()
    ):

        normalized_values.append(
            normalize_value(
                value
            )
        )


    return Counter(
        normalized_values
    )


# =========================================================
# COMPARE MODEL RESULT TO TRUSTED RESULT
# =========================================================

def compare_results(
    actual,
    expected,
):

    actual_counter = (
        dataframe_counter(
            actual
        )
    )


    expected_counter = (
        dataframe_counter(
            expected
        )
    )


    missing_values = []


    for (
        expected_value,
        expected_count,
    ) in expected_counter.items():

        actual_count = (
            actual_counter[
                expected_value
            ]
        )


        if (
            actual_count
            < expected_count
        ):

            missing_values.append(
                {
                    "value":
                        repr(
                            expected_value
                        ),

                    "expected_count":
                        expected_count,

                    "actual_count":
                        actual_count,
                }
            )


    is_correct = (
        len(
            missing_values
        )
        == 0
    )


    return (
        is_correct,
        missing_values,
    )


# =========================================================
# SERIALIZE DATAFRAME
# =========================================================

def dataframe_to_json(
    dataframe,
):

    if dataframe is None:

        return "[]"


    clean_dataframe = (
        dataframe.where(
            pd.notnull(
                dataframe
            ),
            None,
        )
    )


    records = (
        clean_dataframe
        .to_dict(
            orient="records"
        )
    )


    return json.dumps(
        records,
        default=str,
        ensure_ascii=False,
    )


# =========================================================
# CLASSIFY FAILURE
# =========================================================

def classify_failure(
    error,
    captured_output,
):

    combined = (
        f"{error}\n"
        f"{captured_output}"
    ).lower()


    if (
        "business-semantic"
        in combined
        or
        "business semantic"
        in combined
    ):

        return (
            "business_semantic"
        )


    if (
        "binder error"
        in combined
        or
        "duckdb validation failed"
        in combined
    ):

        return (
            "sql_validation"
        )


    if (
        "timed out"
        in combined
        or
        "timeout"
        in combined
    ):

        return (
            "model_timeout"
        )


    if (
        "structured output"
        in combined
        or
        "invalid json"
        in combined
    ):

        return (
            "model_output_format"
        )


    if (
        "safety validation"
        in combined
        or
        "unsafe"
        in combined
    ):

        return (
            "sql_safety"
        )


    return (
        "other"
    )


# =========================================================
# SAVE FAILURE REPORT
# =========================================================

def save_failure_report(
    benchmark_id,
    question,
    exception_text,
    captured_output,
    expected_dataframe=None,
    actual_dataframe=None,
    generated_sql="",
    missing_values=None,
):

    FAILURE_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )


    path = (
        FAILURE_DIR
        / f"{benchmark_id}.txt"
    )


    with open(
        path,
        "w",
        encoding="utf-8",
    ) as file:

        file.write(
            f"BENCHMARK ID: "
            f"{benchmark_id}\n\n"
        )


        file.write(
            "QUESTION:\n"
        )

        file.write(
            f"{question}\n\n"
        )


        file.write(
            "GENERATED SQL:\n"
        )

        file.write(
            generated_sql
            if generated_sql
            else "(none)"
        )

        file.write(
            "\n\n"
        )


        if exception_text:

            file.write(
                "ERROR:\n"
            )

            file.write(
                exception_text
            )

            file.write(
                "\n\n"
            )


        if (
            expected_dataframe
            is not None
        ):

            file.write(
                "EXPECTED RESULT:\n"
            )

            file.write(
                expected_dataframe
                .to_string(
                    index=False
                )
            )

            file.write(
                "\n\n"
            )


        if (
            actual_dataframe
            is not None
        ):

            file.write(
                "ACTUAL RESULT:\n"
            )

            file.write(
                actual_dataframe
                .to_string(
                    index=False
                )
            )

            file.write(
                "\n\n"
            )


        if missing_values:

            file.write(
                "MISSING EXPECTED VALUES:\n"
            )

            file.write(
                json.dumps(
                    missing_values,
                    indent=2,
                )
            )

            file.write(
                "\n\n"
            )


        if captured_output:

            file.write(
                "CAPTURED AGENT OUTPUT:\n"
            )

            file.write(
                captured_output
            )


    return path


