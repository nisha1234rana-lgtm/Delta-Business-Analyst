# =========================================================
# BUILD SUMMARY
# =========================================================

def build_summary(
    dataframe,
):

    total_questions = (
        len(
            dataframe
        )
    )


    execution_successes = int(
        dataframe[
            "execution_success"
        ].sum()
    )


    correct_answers = int(
        dataframe[
            "answer_correct"
        ].sum()
    )


    if total_questions:

        execution_success_rate = (
            100.0
            * execution_successes
            / total_questions
        )


        answer_accuracy = (
            100.0
            * correct_answers
            / total_questions
        )


    else:

        execution_success_rate = 0.0

        answer_accuracy = 0.0


    # =====================================================
    # ACCURACY BY DIFFICULTY
    # =====================================================

    difficulty_accuracy = {}


    for difficulty in [
        "easy",
        "medium",
        "hard",
    ]:

        subset = (
            dataframe[
                dataframe[
                    "difficulty"
                ]
                == difficulty
            ]
        )


        if len(
            subset
        ):

            accuracy = (
                100.0
                * subset[
                    "answer_correct"
                ].sum()
                / len(
                    subset
                )
            )


            difficulty_accuracy[
                difficulty
            ] = round(
                float(
                    accuracy
                ),
                2,
            )


    # =====================================================
    # ACCURACY BY CATEGORY
    # =====================================================

    category_accuracy = {}


    categories = sorted(
        dataframe[
            "category"
        ].unique()
    )


    for category in categories:

        subset = (
            dataframe[
                dataframe[
                    "category"
                ]
                == category
            ]
        )


        accuracy = (
            100.0
            * subset[
                "answer_correct"
            ].sum()
            / len(
                subset
            )
        )


        category_accuracy[
            category
        ] = round(
            float(
                accuracy
            ),
            2,
        )


    # =====================================================
    # FAILURE TYPES
    # =====================================================

    failed_rows = (
        dataframe[
            dataframe[
                "answer_correct"
            ]
            == False
        ].copy()
    )


    if len(
        failed_rows
    ):

        failed_rows[
            "failure_type"
        ] = (
            failed_rows[
                "failure_type"
            ]
            .replace(
                "",
                "incorrect_result",
            )
        )


        failure_counts = (
            failed_rows[
                "failure_type"
            ]
            .value_counts()
            .to_dict()
        )


    else:

        failure_counts = {}


    # =====================================================
    # SUMMARY
    # =====================================================

    summary = {

        "total_questions":
            total_questions,

        "execution_successes":
            execution_successes,

        "execution_success_rate_pct":
            round(
                execution_success_rate,
                2,
            ),

        "correct_answers":
            correct_answers,

        "answer_accuracy_pct":
            round(
                answer_accuracy,
                2,
            ),

        "average_attempts":
            round(
                float(
                    dataframe[
                        "attempts"
                    ].mean()
                ),
                2,
            ),

        "average_latency_seconds":
            round(
                float(
                    dataframe[
                        "latency_seconds"
                    ].mean()
                ),
                2,
            ),

        "difficulty_accuracy_pct":
            difficulty_accuracy,

        "category_accuracy_pct":
            category_accuracy,

        "failure_counts":
            failure_counts,
    }


    RESULTS_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )


    with open(
        SUMMARY_PATH,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            summary,
            file,
            indent=2,
        )


    return summary


