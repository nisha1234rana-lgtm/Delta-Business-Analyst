def main():

    parser = argparse.ArgumentParser(
        description=(
            "Evaluate the Delta "
            "NL-to-SQL agent."
        )
    )


    parser.add_argument(
        "--limit",
        type=int,
        default=None,
        help=(
            "Run only the first N "
            "benchmark questions."
        ),
    )


    parser.add_argument(
        "--ids",
        type=str,
        default=None,
        help=(
            "Comma-separated benchmark IDs. "
            "Example: SQL001,SQL005"
        ),
    )


    args = (
        parser.parse_args()
    )


    print("=" * 80)
    print("DELTA BUSINESS ANALYST")
    print("NL → SQL BENCHMARK")
    print("=" * 80)


    # =====================================================
    # VERIFY DATABASE
    # =====================================================

    if not DB_PATH.exists():

        raise FileNotFoundError(
            f"DuckDB database not found:\n"
            f"{DB_PATH}"
        )


    # =====================================================
    # LOAD BENCHMARK
    # =====================================================

    rows = (
        load_benchmark()
    )


    # =====================================================
    # APPLY CLI FILTERS
    # =====================================================

    rows = (
        filter_rows(
            rows=rows,
            limit=args.limit,
            ids=args.ids,
        )
    )


    if not rows:

        raise RuntimeError(
            "No benchmark questions "
            "were selected."
        )


    print(
        f"\nQuestions selected: "
        f"{len(rows)}"
    )


    print(
        "\nRunning benchmark...\n"
    )


    # =====================================================
    # RUN QUESTIONS
    # =====================================================

    results = []


    benchmark_start = (
        time.perf_counter()
    )


    for index, row in enumerate(
        rows,
        start=1,
    ):

        result = (
            run_one(
                row
            )
        )


        results.append(
            result
        )


        # ================================================
        # SAVE CHECKPOINT AFTER EVERY QUESTION
        # ================================================
        #
        # This means if:
        # - Ollama freezes
        # - PowerShell closes
        # - laptop restarts
        # - benchmark is interrupted
        #
        # all completed results remain saved.
        # ================================================

        save_checkpoint(
            results
        )


        print(
            f"         checkpoint "
            f"{index}/{len(rows)} saved"
        )


    # =====================================================
    # TOTAL BENCHMARK TIME
    # =====================================================

    total_seconds = (
        time.perf_counter()
        - benchmark_start
    )


    # =====================================================
    # SAVE FINAL RESULTS
    # =====================================================

    dataframe = (
        save_results(
            results
        )
    )


    # =====================================================
    # BUILD FINAL SUMMARY
    # =====================================================

    summary = (
        build_summary(
            dataframe
        )
    )


    summary[
        "total_benchmark_runtime_seconds"
    ] = round(
        total_seconds,
        2,
    )


    # =====================================================
    # SAVE SUMMARY WITH TOTAL RUNTIME
    # =====================================================

    RESULTS_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )


    with open(
        SUMMARY_PATH,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            summary,
            file,
            indent=2,
        )


    # =====================================================
    # PRINT SUMMARY
    # =====================================================

    print_summary(
        summary
    )


    print(
        "\nTotal benchmark runtime: "
        f"{total_seconds:.2f}s"
    )


# =========================================================
# ENTRY POINT
# =========================================================

if __name__ == "__main__":

    main()