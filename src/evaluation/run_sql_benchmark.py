# FILTER BENCHMARK ROWS
# =========================================================

def filter_rows(
    rows,
    limit=None,
    ids=None,
):

    selected_rows = (
        rows
    )


    if ids:

        wanted_ids = {
            benchmark_id
            .strip()
            .upper()

            for benchmark_id
            in ids.split(",")

            if benchmark_id.strip()
        }


        selected_rows = [

            row

            for row
            in selected_rows

            if (
                row[
                    "id"
                ]
                .strip()
                .upper()
                in wanted_ids
            )
        ]


    if limit:

        selected_rows = (
            selected_rows[
                :limit
            ]
        )


    return selected_rows


